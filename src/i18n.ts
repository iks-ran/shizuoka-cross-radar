export type MessageKey = keyof (typeof messages)['en']

export const translate = (locale: Locale, key: MessageKey, values: Record<string, string | number> = {}): string =>
  Object.entries(values).reduce(
    (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
    messages[locale][key] as string,
  )

export const detectLocale = (language = navigator.language): Locale => {
  if (language.toLowerCase().startsWith('ja')) return 'ja'
  if (language.toLowerCase().startsWith('zh')) return 'zh-CN'
  return 'en'
}

export const intlLocale = (locale: Locale): string => (locale === 'zh-CN' ? 'zh-CN' : locale === 'ja' ? 'ja-JP' : 'en-US')
